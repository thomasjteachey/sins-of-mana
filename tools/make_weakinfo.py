"""Tiles for the enemy weakness lines (bars.asm WeakDraw) -> build/weakinfo.asm.

The lines are built at runtime from the targeted enemy's own record: +$D1 repel,
+$D2 drain, +$D3 void, +$D4 half, +$D5 weak, one bit per element (the game's
monster table at $D1:0011, 36 bytes per type, holds the same five bytes). This file
only provides the words: element names by bit, the five labels, "none", "all",
"all but ". Each string: length byte, then tile numbers.
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_levelinfo import tile

ELEMENTS = ['Earth', 'Air', 'Water', 'Fire', 'Dark', 'Holy', 'Moon', 'Leaf']   # bits 0-7
LABELS = ['Weak: ', 'Drain: ', 'Repel: ', 'Void: ', 'Half: ']                 # WeakSeg's $11


def lstr(text, size):
    assert len(text) < size, text
    out = [len(text)] + [tile(c) for c in text]
    return out + [0] * (size - len(out))


def db(values):
    return '\tdb ' + ', '.join('$%02X' % v for v in values)


def write(path):
    out = ['; generated by tools/make_weakinfo.py', 'WeakComma = $%04X' % tile(','),
           'WeakNames:                ; 6 bytes per element bit']
    out += [db(lstr(e, 6)) + '   ; ' + e for e in ELEMENTS]
    out.append('WeakLabels:               ; 8 bytes per category')
    out += [db(lstr(l, 8)) + '   ; ' + l for l in LABELS]
    for name, text in (('WeakNone', 'none'), ('WeakAll', 'all'), ('WeakBut', 'all but ')):
        out.append(name + ':')
        out.append(db(lstr(text, len(text) + 1)))
    open(path, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    write(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'build', 'weakinfo.asm'))
