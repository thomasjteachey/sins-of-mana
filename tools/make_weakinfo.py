"""Enemy weakness texts for the target picker (bars.asm WeakPanel) -> build/weakinfo.asm.

Source: monster_bosses.xls, sheet "Enemy" (row 1 = enemy type 0). Each enemy gets up
to 3 lines of 30 cells under the target bar:  "Weak: Earth" then its resistances
("Drain: Dark  Half: Water"). Stream bytes: tile numbers, $00 end, $01 next line,
$02 green (labels), $03 white.

Usage: python tools/make_weakinfo.py   (prints the texts; build.py writes the asm)
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_levelinfo import tile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XLS = os.path.join(ROOT, 'monster_bosses.xls')
WIDTH, LINES = 30, 3
NAMES = {'fire': 'Fire', 'water': 'Water', 'earth': 'Earth', 'air': 'Air', 'holy': 'Holy',
         'dark': 'Dark', 'moon': 'Moon', 'leaf': 'Leaf', 'physical': 'Phys',
         'magic': 'Magic', 'all': 'all'}
END, NEWLINE, GREEN, WHITE = 0, 1, 2, 3


def elements(cell):
    cell = cell.strip()
    if not cell:
        return []
    if cell == 'all except holy and dark':
        return ['all but Holy', 'Dark']
    out = []
    for e in cell.split(','):
        e = e.strip()
        if e == 'counter':                       # weak to counter attacks: not an element
            continue
        out.append(NAMES[e])
    return out


def enemies():
    import xlrd
    s = xlrd.open_workbook(XLS).sheet_by_name('Enemy')
    head = s.row_values(0)
    col = {name: head.index(name) for name in ('Name', 'Repel', 'Drain', 'Void', 'Half', 'Weak')}
    for r in range(1, s.nrows):
        v = s.row_values(r)
        yield r - 1, v[col['Name']], {k: elements(str(v[i])) for k, i in col.items() if k != 'Name'}


def segments(info):
    """[(label, [elements])] in display order: weak first, then what it shrugs off."""
    drain = info['Drain']
    repel = [e for e in info['Repel'] if e not in drain]
    segs = [('Weak', info['Weak'] or ['none'])]
    for label, els in (('Drain', drain), ('Repel', repel), ('Void', info['Void']), ('Half', info['Half'])):
        if els:
            segs.append((label, els))
    return segs


def layout(segs):
    """Lines of [(text, green?)] pieces, at most WIDTH cells each. The weak segment
    always starts line 1, the resistances line 2; long lists wrap after a comma."""
    lines, cur, used = [], [], 0

    def newline():
        nonlocal cur, used
        lines.append(cur)
        cur, used = [], 0

    for n, (label, els) in enumerate(segs):
        head = label + ': '
        if n == 1 and cur:
            newline()
        elif cur and used + 2 + len(head) + sum(len(e) + 2 for e in els) - 2 > WIDTH:
            newline()
        if cur:
            cur.append(('  ', False))
            used += 2
        cur.append((head, True))
        used += len(head)
        for i, e in enumerate(els):
            word = e + (',' if i < len(els) - 1 else '')
            if i and used + 1 + len(word) > WIDTH:
                newline()
            elif i:
                cur.append((' ', False))
                used += 1
            cur.append((word, False))
            used += len(word)
    if cur:
        lines.append(cur)
    assert len(lines) <= LINES and all(sum(len(t) for t, _ in l) <= WIDTH for l in lines), lines
    return lines


def stream(lines):
    out, green = [], None
    for k, line in enumerate(lines):
        if k:
            out.append(NEWLINE)
        for text, g in line:
            if g != green:
                out.append(GREEN if g else WHITE)
                green = g
            out += [tile(ch) for ch in text]
    assert all(t > WHITE for t in out if t not in (NEWLINE, GREEN, WHITE))
    return out + [END]


def write(path):
    rows = list(enemies())
    out = ['; generated by tools/make_weakinfo.py from monster_bosses.xls',
           'WeakCount = %d' % len(rows), 'WeakPtr:                 ; by enemy type']
    texts, labels = {}, []
    for t, name, info in rows:
        s = tuple(stream(layout(segments(info))))
        if s not in texts:
            texts[s] = 'WeakText%d' % len(texts)
        labels.append((texts[s], name))
    for lab, name in labels:
        out.append('\tdw %s   ; %s' % (lab, name))
    for s, lab in texts.items():
        out.append('%s: db %s' % (lab, ', '.join('$%02X' % b for b in s)))
    open(path, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    for t, name, info in enemies():
        lines = layout(segments(info))
        print('%02X %-16s | %s' % (t, name, ' / '.join(''.join(x for x, _ in l) for l in lines)))
