"""Tiles for the info lines under the target / ring bar (bars.asm WeakDraw) -> build/weakinfo.asm.

Enemy weaknesses:
The lines are built at runtime from the targeted enemy's own record: +$D1 repel,
+$D2 drain, +$D3 void, +$D4 half, +$D5 weak, one bit per element (the game's
monster table at $D1:0011, 36 bytes per type, holds the same five bytes). This file
only provides the words: element names by bit, the labels, "none", "all",
"all but ". Each string: length byte, then tile numbers.

Spell details: element and cast time come from the game's spell table ($D1:9936 + id*17:
+0 MP, +1 cast time, +3 element bits); what the spell does and its possible upgrades from
the mod's skills_consumables_traps.xls ("spells"), as streams per spell id (SpellPtr):
tiles, $00 end, $01 next line, $02 green, $03 white.
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_levelinfo import tile

ELEMENTS = ['Earth', 'Air', 'Water', 'Fire', 'Dark', 'Holy', 'Moon', 'Leaf']   # bits 0-7
LABELS = ['Weak: ', 'Drain: ', 'Repel: ', 'Void: ', 'Half: ', 'Element: ']     # WeakSeg's $11
WIDTH, ROWS = 30, 7          # spell text rows under the element / cast line (rows 9-15)
XLS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'skills_consumables_traps.xls')
ALIAS = {'trans-shape': 'transshape', 'lamian naga': 'lamia naga', 'arrow': 'arrows', 'spike': 'spikes',
         'rock fall': 'rockfall', 'landmine': 'land mine', 'cresent': 'crescent', 'flame breath': 'fire breath',
         'analyze': 'analyse'}


def lstr(text, size):
    assert len(text) < size, text
    out = [len(text)] + [tile(c) for c in text]
    return out + [0] * (size - len(out))


def db(values):
    return '\tdb ' + ', '.join('$%02X' % v for v in values)


def clean(text):
    text = str(text).strip().replace('½', '1/2').replace(';', ',').replace('  ', ' ')
    return text[:1].upper() + text[1:]


def wrap(words, width, first=0):
    """Greedy wrap of words into lines of `width` cells; the first line already has `first` used."""
    lines, cur, used = [], [], first
    for w in words.split(' '):
        if cur and used + 1 + len(w) > width:
            lines.append(' '.join(cur))
            cur, used = [], 0
        used += len(w) + (1 if cur else 0)
        cur.append(w)
    lines.append(' '.join(cur))
    return lines


def spell_texts():
    """{spell id: [line, ...]}, each line a list of (text, green?) pieces."""
    import xlrd
    from make_levelinfo import SPELL_NAMES
    sh = xlrd.open_workbook(XLS).sheet_by_name('spells')
    head = sh.row_values(0)
    col = {k: head.index(k) for k in ('Spell', 'Effect', 'Special', 'Possible Upgrades')}
    rows = {}
    for r in range(1, sh.nrows):
        v = sh.row_values(r)
        k = str(v[col['Spell']]).strip().lower()
        rows[ALIAS.get(k, k)] = v
    out = {}
    for i, name in SPELL_NAMES.items():
        v = rows.get(name.lower())
        if not v:
            continue
        what = clean(v[col['Effect']])
        special = str(v[col['Special']]).strip()
        if special and not special.lower().startswith('can be learned'):   # it's in the ring: learned
            what = what.rstrip('.') + '. ' + clean(special)
        lines = [[(l, False)] for l in wrap(what, WIDTH)]
        up = str(v[col['Possible Upgrades']]).strip()
        if up:
            label = 'Upgrades: '
            parts = wrap(clean(up), WIDTH, len(label))
            lines.append([(label, True), (parts[0], False)])
            lines += [[(l, False)] for l in parts[1:]]
        assert len(lines) <= ROWS and all(sum(len(t) for t, _ in l) <= WIDTH for l in lines), (name, lines)
        out[i] = lines
    return out


def stream(lines):
    out, green = [], None
    for k, line in enumerate(lines):
        if k:
            out.append(1)
        for text, g in line:
            if g != green:
                out.append(2 if g else 3)
                green = g
            out += [tile(ch) for ch in text]
    assert all(t > 3 for t in out if t not in (1, 2, 3))
    return out + [0]


def write(path):
    out = ['; generated by tools/make_weakinfo.py', 'WeakComma = $%04X' % tile(','),
           'WeakNames:                ; 6 bytes per element bit']
    out += [db(lstr(e, 6)) + '   ; ' + e for e in ELEMENTS]
    out.append('WeakLabels:               ; 16 bytes per category')
    out += [db(lstr(l, 16)) + '   ; ' + l for l in LABELS]
    for name, text in (('WeakNone', 'none'), ('WeakAll', 'all'), ('WeakBut', 'all but '),
                       ('WeakPhys', 'Physical'), ('WeakCast', 'Cast: ')):
        out.append(name + ':')
        out.append(db(lstr(text, len(text) + 1)))
    texts = spell_texts()
    top = max(texts) if texts else 0
    out.append('SpellPtr:                 ; by spell id: what it does, upgrades (0 = no text)')
    out.append('	dw ' + ', '.join('SpellText%02X' % i if i in texts else '$0000' for i in range(top + 1)))
    out.append('SpellText:')
    for i, lines in sorted(texts.items()):
        out.append('SpellText%02X:   ; %s' % (i, ' / '.join(''.join(t for t, _ in l) for l in lines)))
        out.append(db(stream(lines)))
    open(path, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    for i, lines in sorted(spell_texts().items()):
        print('%02X %d | %s' % (i, len(lines), ' / '.join(''.join(t for t, _ in l) for l in lines)))
    write(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'build', 'weakinfo.asm'))
